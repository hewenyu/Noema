import Foundation

/// Decides, from pasteboard metadata alone, whether a change may be recorded and what to
/// read. Pure: no AppKit, no pasteboard access. Checks run in this order and the first hit
/// wins: secure input, Noema's own paste-back, privacy marker types (pasteboard-level and
/// per item), the source-app blocklist, file-only copies, then the payload choice.
public struct ClipboardPrivacyFilter: Sendable, Hashable {
    /// Written by every Noema paste-back next to `org.nspasteboard.TransientType`.
    public static let selfPasteType = "dev.noema.clipboard.self-paste"
    public static let transientType = "org.nspasteboard.TransientType"

    /// The nspasteboard.org markers and the older private markers password managers and
    /// text expanders still write.
    public static let markerTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        transientType,
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// Any type equal to or starting with one of these is a 1Password marker.
    public static let markerPrefixes = ["com.agilebits.onepassword", "com.1password."]

    /// Password managers whose copies are never recorded (compared case-insensitively).
    public static let builtInBlockedBundleIDs = [
        "com.apple.Passwords", "com.apple.keychainaccess",
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "com.dashlane.Dashlane", "com.lastpass.LastPass",
        "org.keepassxc.keepassxc", "com.enpass.Enpass", "com.strongboxsafe.strongbox", "com.nordpass.macos",
    ]

    public static let textTypes = ["public.utf8-plain-text", "public.utf16-plain-text", "NSStringPboardType"]
    /// In preference order: PNG is stored as is, the others are transcoded to PNG.
    public static let imageTypes = ["public.png", "public.tiff", "public.jpeg", "public.heic"]
    public static let fileURLTypes: Set<String> = ["public.file-url", "NSFilenamesPboardType"]

    /// Lowercased built-in and user bundle IDs.
    public private(set) var blockedBundleIDs: Set<String>

    public init(additionalBlockedBundleIDs: [String] = []) {
        blockedBundleIDs = Set((Self.builtInBlockedBundleIDs + additionalBlockedBundleIDs).map { $0.lowercased() })
    }

    public func isBlocked(bundleID: String?) -> Bool {
        guard let bundleID else { return false }
        return blockedBundleIDs.contains(bundleID.lowercased())
    }

    public static func isMarker(_ type: String) -> Bool {
        markerTypes.contains(type) || markerPrefixes.contains { type.hasPrefix($0) }
    }

    /// The decision for `snapshot`; reads only its metadata, never its payload closures.
    public func evaluate(_ snapshot: ClipboardCaptureSnapshot, ignoredSelfChangeCounts: Set<Int> = []) -> ClipboardCaptureDecision {
        if snapshot.isSecureInputActive { return .skip(.secureInput) }
        let types = snapshot.allTypes
        if ignoredSelfChangeCounts.contains(snapshot.changeCount) || types.contains(Self.selfPasteType) {
            return .skip(.selfPaste)
        }
        if let marker = types.sorted().first(where: Self.isMarker) { return .skip(.privacyMarker(marker)) }
        if let bundleID = snapshot.source?.bundleID, isBlocked(bundleID: bundleID) { return .skip(.blockedSource(bundleID)) }
        let hasText = Self.textTypes.contains(where: types.contains)
        let hasFileURL = !types.isDisjoint(with: Self.fileURLTypes)
        // A Finder copy carries the file name as text and the icon as TIFF: keep the text,
        // never the icon, and never read the file itself.
        if hasText { return .capture(.text) }
        if hasFileURL { return .skip(.fileOnly) }
        if let image = Self.imageTypes.first(where: types.contains) { return .capture(.image(type: image)) }
        return .skip(.unsupported)
    }

    /// `.sensitive` when `text` holds an obvious unmarked secret: a PEM private key, an
    /// OpenAI-style `sk-` key, a GitHub token, an AWS access key ID, or a Slack token.
    public static func classifySensitivity(_ text: String) -> ClipboardSensitivity {
        let patterns: [Regex<Substring>] = [
            #/-----BEGIN [A-Z0-9 ]*PRIVATE KEY-----/#,
            #/sk-[A-Za-z0-9_\-]{16,}/#,
            #/ghp_[A-Za-z0-9]{20,}/#,
            #/github_pat_/#,
            #/AKIA[0-9A-Z]{16}/#,
            #/xox[baprs]-/#,
        ]
        return patterns.contains { text.contains($0) } ? .sensitive : .standard
    }
}
