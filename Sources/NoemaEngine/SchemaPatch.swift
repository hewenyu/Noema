import CryptoKit
import Foundation

/// How `noema-rime-deployer` adds a translator to a schema's `<schema>.custom.yaml` patch in
/// its staging directory without ever editing the user's YAML.
///
/// With no user patch it writes a fresh one. Otherwise the user's file moves, byte for
/// byte, to `<schema>.noema-user-custom.yaml` and the staged `<schema>.custom.yaml` becomes a
/// wrapper whose `patch` mapping is `__include: "<schema>.noema-user-custom:/patch?"` plus
/// one key appending the translator. librime's own YAML parser and config compiler read the
/// user's file, so every legal YAML form (block or flow `patch:`, inline sequences, anchors,
/// CRLF) means exactly what it meant before. Under `__include` a local key that ends in `/+`
/// is a merge operator on the included map, not a patch path, so the appending key is
/// `engine/translators/@next` (else `engine/translators/@after last`), whichever the user's
/// patch does not already use; librime applies patch keys in sorted order, so either runs
/// after every user key on `engine` or `engine/translators`.
public enum SchemaPatch {
    /// The key of a fresh patch: librime appends its sequence to the translator list.
    public static let appendTranslatorKey = "engine/translators/+"
    /// Keys a wrapper may append with, in preference order (`appendKey(avoiding:)`).
    public static let wrapperAppendKeys = ["engine/translators/@next", "engine/translators/@after last"]

    /// The config ID the user's patch is staged under, beside the wrapper.
    public static func userPatchConfigID(schemaID: String) -> String { "\(schemaID).noema-user-custom" }

    /// A new `<schema>.custom.yaml` that appends `component`.
    public static func freshPatch(appending component: String) -> String {
        "patch:\n  \"\(appendTranslatorKey)\":\n    - \"\(component)\"\n"
    }

    /// The wrapper `<schema>.custom.yaml`: the user's patch (`userConfigID:/patch`, optional)
    /// with `component` appended, or nil when the user's patch already uses every
    /// `wrapperAppendKeys` spelling. `userPatchKeys` are the top-level keys of the user's
    /// `patch` mapping as librime parsed them.
    public static func wrapper(appending component: String, userConfigID: String, userPatchKeys: [String]) -> String? {
        guard let key = appendKey(avoiding: userPatchKeys) else { return nil }
        return """
            # Generated by noema-rime-deployer: the user's own patch, then \(component).
            patch:
              __include: "\(userConfigID):/patch?"
              "\(key)": "\(component)"

            """
    }

    /// The first `wrapperAppendKeys` entry not in `userPatchKeys`.
    public static func appendKey(avoiding userPatchKeys: [String]) -> String? {
        wrapperAppendKeys.first { !userPatchKeys.contains($0) }
    }

    /// Whether a line of `text` outside a `#` comment line already names `component`, so the
    /// user's patch is staged unchanged (the deployer still checks the compiled list).
    public static func names(_ component: String, in text: String) -> Bool {
        text.split(whereSeparator: \.isNewline).contains { line in
            !line.drop { $0 == " " || $0 == "\t" }.hasPrefix("#") && line.contains(component)
        }
    }
}

extension DeployManifest {
    /// Lowercase hex SHA-256 of `data`, or nil for nil.
    public static func sha256(of data: Data?) -> String? {
        data.map { SHA256.hash(data: $0).map { String(format: "%02x", $0) }.joined() }
    }
}
