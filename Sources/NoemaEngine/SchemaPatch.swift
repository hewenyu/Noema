import CryptoKit
import Foundation

/// The `<schema>.custom.yaml` patch `noema-rime-deployer` stages for every deployment,
/// without ever editing the user's YAML. It always disables the schema's `v` recognizer
/// patterns (`disabledRecognizerKeys`: NoemaIME owns a leading `v` for v-mode, and an
/// upstream `^v.*$` pattern would otherwise claim it) and, with a learned-phrase
/// translator, appends that translator.
///
/// With no user patch it writes a fresh one. Otherwise the user's file moves, byte for
/// byte, to `<schema>.noema-user-custom.yaml` and the staged `<schema>.custom.yaml` becomes a
/// wrapper whose `patch` mapping is `__include: "<schema>.noema-user-custom:/patch?"` plus
/// Noema's keys. librime's own YAML parser and config compiler read the user's file, so
/// every legal YAML form (block or flow `patch:`, inline sequences, anchors, CRLF) means
/// exactly what it meant before. Under `__include` a local key that ends in `/+` is a merge
/// operator on the included map, not a patch path, so the appending key is
/// `engine/translators/@next` (else `engine/translators/@after last`), whichever the user's
/// patch does not already use; librime applies patch keys in sorted order, so either runs
/// after every user key on `engine` or `engine/translators`, and the recognizer keys run
/// after any user key on `recognizer` or `recognizer/patterns`.
public enum SchemaPatch {
    /// The key of a fresh patch: librime appends its sequence to the translator list.
    public static let appendTranslatorKey = "engine/translators/+"
    /// Keys a wrapper may append with, in preference order (`appendKey(avoiding:)`).
    public static let wrapperAppendKeys = ["engine/translators/@next", "engine/translators/@after last"]
    /// Recognizer patterns every staged patch sets to null, so no upstream pattern (万象's
    /// and 雾凇's `v` modes) claims input that starts with `v`. `speller/alphabet` is left
    /// alone: `lv` and `nv` still spell 绿 and 女.
    public static let disabledRecognizerKeys = ["recognizer/patterns/v", "recognizer/patterns/v_mode"]
    /// The `DeployManifest.schemaPatches` entry of a build compiled with
    /// `disabledRecognizerKeys`. A build without it predates v-mode and is redeployed.
    public static let vRecognizersDisabledPatchID = "noema.recognizer-v-disabled.v1"
    /// Every patch ID the current deployer applies; `RimeEngine` redeploys a build whose
    /// manifest lacks one.
    public static let requiredPatchIDs = [vRecognizersDisabledPatchID]

    /// The config ID the user's patch is staged under, beside the wrapper.
    public static func userPatchConfigID(schemaID: String) -> String { "\(schemaID).noema-user-custom" }

    /// A new `<schema>.custom.yaml` that disables the `v` recognizers and, when given,
    /// appends `component`.
    public static func freshPatch(appending component: String? = nil) -> String {
        var text = "patch:\n"
        if let component { text += "  \"\(appendTranslatorKey)\":\n    - \"\(component)\"\n" }
        for key in disabledRecognizerKeys { text += "  \"\(key)\": ~\n" }
        return text
    }

    /// The wrapper `<schema>.custom.yaml`: the user's patch (`userConfigID:/patch`, optional),
    /// the disabled `v` recognizers, and `component` appended when given; nil when
    /// `component` is given and the user's patch already uses every `wrapperAppendKeys`
    /// spelling. `userPatchKeys` are the top-level keys of the user's `patch` mapping as
    /// librime parsed them.
    public static func wrapper(appending component: String?, userConfigID: String, userPatchKeys: [String]) -> String? {
        var text = """
            # Generated by noema-rime-deployer: the user's own patch, then Noema's keys.
            patch:
              __include: "\(userConfigID):/patch?"

            """
        if let component {
            guard let key = appendKey(avoiding: userPatchKeys) else { return nil }
            text += "  \"\(key)\": \"\(component)\"\n"
        }
        for key in disabledRecognizerKeys { text += "  \"\(key)\": ~\n" }
        return text + "\n"
    }

    /// The first `wrapperAppendKeys` entry not in `userPatchKeys`.
    public static func appendKey(avoiding userPatchKeys: [String]) -> String? {
        wrapperAppendKeys.first { !userPatchKeys.contains($0) }
    }

    /// Whether a line of `text` outside a `#` comment line already names `component`, so the
    /// wrapper does not append it again (the deployer still checks the compiled list).
    public static func names(_ component: String, in text: String) -> Bool {
        text.split(whereSeparator: \.isNewline).contains { line in
            !line.drop { $0 == " " || $0 == "\t" }.hasPrefix("#") && line.contains(component)
        }
    }
}

extension DeployManifest {
    /// Lowercase hex SHA-256 of `data`, or nil for nil.
    public static func sha256(of data: Data?) -> String? {
        data.map { SHA256.hash(data: $0).map { String(format: "%02x", $0) }.joined() }
    }

    /// Whether the build was compiled with every patch the current deployer applies
    /// (`SchemaPatch.requiredPatchIDs`).
    public var carriesRequiredSchemaPatches: Bool {
        Set(schemaPatches ?? []).isSuperset(of: SchemaPatch.requiredPatchIDs)
    }
}
