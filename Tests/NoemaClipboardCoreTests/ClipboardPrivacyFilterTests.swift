import Foundation
@testable import NoemaClipboardCore
import Testing

/// The privacy filter decides from metadata alone, in a fixed order, and never reads a
/// payload of a filtered copy.
@Suite struct ClipboardPrivacyFilterTests {
    /// A snapshot whose payload closures count every read.
    final class ReadSpy {
        var stringReads = 0
        var dataReads = 0

        func snapshot(
            changeCount: Int = 7, types: [String] = ["public.utf8-plain-text"], itemTypes: [[String]] = [],
            source: ClipboardSourceApp? = ClipboardSourceApp(bundleID: "com.apple.TextEdit", name: "TextEdit"), secure: Bool = false
        ) -> ClipboardCaptureSnapshot {
            ClipboardCaptureSnapshot(
                changeCount: changeCount, pasteboardTypes: types, itemTypes: itemTypes, source: source, isSecureInputActive: secure,
                readString: { [self] in stringReads += 1; return "secret" },
                readData: { [self] _ in dataReads += 1; return Data([1]) })
        }
    }

    static let markers = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type",
        "com.agilebits.onepassword", "com.agilebits.onepassword.item-uuid", "com.1password.secret",
    ]

    @Test(arguments: markers)
    func markerAtPasteboardLevelSkips(_ marker: String) {
        let spy = ReadSpy()
        let decision = ClipboardPrivacyFilter().evaluate(spy.snapshot(types: ["public.utf8-plain-text", marker]))
        #expect(decision == .skip(.privacyMarker(marker)))
        #expect(spy.stringReads == 0 && spy.dataReads == 0)
    }

    @Test(arguments: markers)
    func markerOnOneItemSkips(_ marker: String) {
        let spy = ReadSpy()
        let snapshot = spy.snapshot(
            types: ["public.utf8-plain-text"], itemTypes: [["public.utf8-plain-text"], ["public.png", marker]])
        #expect(ClipboardPrivacyFilter().evaluate(snapshot) == .skip(.privacyMarker(marker)))
        #expect(spy.stringReads == 0 && spy.dataReads == 0)
    }

    @Test func selfPasteMarkerAndChangeCountSkip() {
        let spy = ReadSpy()
        let filter = ClipboardPrivacyFilter()
        #expect(filter.evaluate(spy.snapshot(types: ["public.utf8-plain-text", ClipboardPrivacyFilter.selfPasteType])) == .skip(.selfPaste))
        #expect(filter.evaluate(spy.snapshot(itemTypes: [[ClipboardPrivacyFilter.selfPasteType]])) == .skip(.selfPaste))
        // A third party stripped the custom types: the change count alone still matches.
        #expect(filter.evaluate(spy.snapshot(changeCount: 41), ignoredSelfChangeCounts: [40, 41]) == .skip(.selfPaste))
        #expect(filter.evaluate(spy.snapshot(changeCount: 42), ignoredSelfChangeCounts: [40, 41]) == .capture(.text))
        #expect(spy.stringReads == 0 && spy.dataReads == 0)
    }

    @Test(arguments: ClipboardPrivacyFilter.builtInBlockedBundleIDs)
    func passwordManagersAreBlockedCaseInsensitively(_ bundleID: String) {
        let spy = ReadSpy()
        let filter = ClipboardPrivacyFilter()
        for variant in [bundleID, bundleID.uppercased(), bundleID.lowercased()] {
            let decision = filter.evaluate(spy.snapshot(source: ClipboardSourceApp(bundleID: variant, name: "Vault")))
            #expect(decision == .skip(.blockedSource(variant)))
        }
        #expect(spy.stringReads == 0 && spy.dataReads == 0)
    }

    @Test func customBundleIDIsBlocked() {
        let spy = ReadSpy()
        let filter = ClipboardPrivacyFilter(additionalBlockedBundleIDs: ["com.Example.Vault"])
        #expect(filter.evaluate(spy.snapshot(source: ClipboardSourceApp(bundleID: "COM.EXAMPLE.VAULT", name: nil))) == .skip(.blockedSource("COM.EXAMPLE.VAULT")))
        #expect(filter.evaluate(spy.snapshot()) == .capture(.text))
        #expect(ClipboardPrivacyFilter().evaluate(spy.snapshot(source: ClipboardSourceApp(bundleID: "com.example.vault", name: nil))) == .capture(.text))
    }

    @Test func secureInputWinsOverEverything() {
        let spy = ReadSpy()
        let decision = ClipboardPrivacyFilter().evaluate(spy.snapshot(types: ["public.utf8-plain-text", "public.png"], secure: true))
        #expect(decision == .skip(.secureInput))
        #expect(spy.stringReads == 0 && spy.dataReads == 0)
    }

    @Test func payloadChoice() {
        let filter = ClipboardPrivacyFilter()
        let spy = ReadSpy()
        #expect(filter.evaluate(spy.snapshot(types: ["public.file-url"])) == .skip(.fileOnly))
        #expect(filter.evaluate(spy.snapshot(types: ["public.file-url", "public.tiff"])) == .skip(.fileOnly), "a Finder icon is not an image copy")
        #expect(filter.evaluate(spy.snapshot(types: ["public.file-url", "public.utf8-plain-text", "public.tiff"])) == .capture(.text))
        #expect(filter.evaluate(spy.snapshot(types: ["public.tiff", "public.png"])) == .capture(.image(type: "public.png")))
        #expect(filter.evaluate(spy.snapshot(types: ["public.tiff"])) == .capture(.image(type: "public.tiff")))
        #expect(filter.evaluate(spy.snapshot(types: ["com.adobe.pdf"])) == .skip(.unsupported))
        #expect(filter.evaluate(spy.snapshot(types: [])) == .skip(.unsupported))
        #expect(spy.stringReads == 0 && spy.dataReads == 0, "evaluate never reads a payload")
    }

    @Test func sensitivityHeuristics() {
        let secrets = [
            "-----BEGIN OPENSSH PRIVATE KEY-----\nb3BlbnNzaC1rZXk=\n-----END OPENSSH PRIVATE KEY-----",
            "-----BEGIN RSA PRIVATE KEY-----", "-----BEGIN PRIVATE KEY-----",
            "export OPENAI_API_KEY=sk-proj-abcdefghijklmnop1234", "ghp_abcdefghijklmnopqrstuvwxyz0123",
            "github_pat_11ABCDEFG", "AKIAIOSFODNN7EXAMPLE", "xoxb-1234-5678",
        ]
        for secret in secrets { #expect(ClipboardPrivacyFilter.classifySensitivity(secret) == .sensitive, "\(secret)") }
        let ordinary = ["你好世界", "sk-short", "ghp_short", "AKIA1234", "ssh-rsa AAAAB3Nza public key", "task-list"]
        for text in ordinary { #expect(ClipboardPrivacyFilter.classifySensitivity(text) == .standard, "\(text)") }
    }
}
